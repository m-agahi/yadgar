class TestStatsAccumulation:
    def test_multiple_pruned_increments_stats(self):
        mems = [
            _mem(i, ["_action_stream"], heat=0.005, confidence=0.1, access_count=0)
            for i in range(5)
        ]
        storage = _storage(*mems)
        stats = {"pruned": 0}
        _memify_prune(storage, _settings(), stats)
        assert stats["pruned"] == 5

    def test_no_prunable_memories_leaves_stats_unchanged(self):
        mem = _mem(99, ["user-created"], heat=1.0)
        storage = _storage(mem)
        stats = {"pruned": 0}
        _memify_prune(storage, _settings(), stats)
        assert stats["pruned"] == 0
