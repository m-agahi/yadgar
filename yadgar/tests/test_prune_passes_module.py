class TestPass1ActionStream:
    def test_cold_low_confidence_unaccessed_deleted(self):
        mem = _mem(1, ["_action_stream"], heat=0.005, confidence=0.1, access_count=0)
        storage = _storage(mem)
        stats = {"pruned": 0}
        _memify_prune(storage, _settings(), stats)
        storage.delete_memory.assert_called_once_with(1)
        assert stats["pruned"] == 1

    def test_protected_skipped(self):
        mem = _mem(
            2, ["_action_stream"], heat=0.005, confidence=0.1, access_count=0, is_protected=True
        )
        storage = _storage(mem)
        stats = {"pruned": 0}
        _memify_prune(storage, _settings(), stats)
        storage.delete_memory.assert_not_called()

    def test_warm_heat_not_pruned(self):
        mem = _mem(3, ["_action_stream"], heat=0.5, confidence=0.1, access_count=0)
        storage = _storage(mem)
        stats = {"pruned": 0}
