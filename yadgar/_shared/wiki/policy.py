# Valid mutability values — the closed set every writer + reader agrees on.
MUTABILITY_FREE = "free"
MUTABILITY_LOCKED = "locked"
MUTABILITY_DERIVED = "derived"
_VALID_MUTABILITY: frozenset[str] = frozenset(
    {MUTABILITY_FREE, MUTABILITY_LOCKED, MUTABILITY_DERIVED}
)

# Public alias of the closed set — ``WikiStore.set_mutability_by_slug`` and
# ``wiki_set_mutability`` validate incoming ``value`` against this rather than
# the private frozenset so the import surface is uniform.
MUTABILITY_VALUES: frozenset[str] = _VALID_MUTABILITY


# Car J (0047 §7 D26): per-type mutability defaults. The policy axis is
# orthogonal to recall_disposition/gate_mode — it gates WRITES at the storage
# chokepoint (``_WikiMixin.update_wiki_page``), not search-time recall.
#
# - adr / adr_superseded → locked: decisions are immutable, the supersede
#   retype (Car G) is the SOLE sanctioned mutator.
# - task / agent_prompt family → free: operational knowledge.
# - wiki_rollup → derived: regenerated by Car K's nightly sweep, not
#   hand-edited.
# - everything else → free (caught by ``get_effective_mutability``'s fallback).
MUTABILITY_BY_TYPE: dict[str, str] = {
    "adr": MUTABILITY_LOCKED,
    "adr_superseded": MUTABILITY_LOCKED,
    "task": MUTABILITY_FREE,
    PAGE_TYPE_AGENT_PROMPT_LEGACY: MUTABILITY_FREE,
    PAGE_TYPE_AGENT_PATTERN: MUTABILITY_FREE,
    PAGE_TYPE_AGENT_DISCIPLINE: MUTABILITY_FREE,
    PAGE_TYPE_AGENT_INDEX: MUTABILITY_FREE,
    "wiki_rollup": MUTABILITY_DERIVED,
}


@dataclass(frozen=True)
class WikiPolicy:
    """Immutable routing policy for a wiki page_type.

    Field order: gate_mode, recall_disposition, dir_scope, merge, storage_scope,
    opt_in_tag. Positional construction is intentional — keep field order
    stable. New fields MUST be appended with defaults so existing 4–6-arg
    positional callers (tests) keep working without changes.
    """

    gate_mode: str
    """``"similarity"`` or ``"identity"``."""

    recall_disposition: str
    """``"include"``, ``"exclude"``, or ``"downweight"``."""

    dir_scope: str
    """``"strict"`` or ``"global"``."""

    merge: str
    """``"allow"`` or ``"never"``."""

    storage_scope: str = "project"
    """``"project"`` — stamped with caller's directory_context (default).
    ``"global"`` — directory_context is overridden to ``"global"`` at write time,
    regardless of what the caller supplied. Used for cross-project shared pages
    (e.g. agent-prompt library) so every project can recall them.

    C2 (#83): enforcement lives in ``WikiStore.add`` — the single write chokepoint
    used by both agent_prompt_save and wiki_add's replay path.
    """

    opt_in_tag: str | None = None
    """Car C1 (0047): per-type opt-in key for the recall exclusion gate.

    ``None`` — the type is excluded UNCONDITIONALLY: no tag the caller passes
    unlocks it. ``agent_index`` (the TOC) uses this — it must never be
    recall-visible (§1.4), and Car I later deletes the TOC page entirely.

    A string value — the ONE tag that unlocks the type when present in the
    caller's ``opt_in_tags``. The page's own ``tags`` field is NOT consulted by
    the exclusion gate; only the TYPE's declared key (ADR-0209 — page_type is
    the policy lever). ``agent_pattern``, ``agent_discipline``, and legacy
    ``agent_prompt`` declare ``"agent-prompt"`` (the documented
    ``recall(tags=["agent-prompt"])`` lookup).
    """

    mutability: str = MUTABILITY_FREE
    """Car J (0047 §7 D25/D26): write-side mutability axis (field #6).

    Values: ``"free"`` | ``"locked"`` | ``"derived"``. The TYPE-level default
    lives in ``MUTABILITY_BY_TYPE``; a per-page ``mutability_override`` on the
    wiki_page row wins over the type default. Enforcement happens at the
    STORAGE chokepoint (``_WikiMixin.update_wiki_page`` + insert/delete for
    symmetry), not at the policy surface — this field is a resolver lever,
    not the enforcement point.

    - ``"free"`` — no enforcement; agent/tool writes allowed.
    - ``"locked"`` — block agent/tool writes; sanctioned server-side
      transitions (Car G supersede retype) pass.
    - ``"derived"`` — block all writes (regenerated, not hand-edited);
      sanctioned transitions pass (Car K nightly sweep deletes + recreates).

    Field appended with a default so existing 4–6-arg positional callers
    (tests across the corpus) keep constructing without error.
    """


