@observe(tier="stage")
def get_policy(page_type: str | None) -> WikiPolicy:
    """Return the ``WikiPolicy`` for *page_type*, or ``DEFAULT_POLICY``.

    Args:
        page_type: The ``page_type`` field from a wiki page.  ``None`` and
            any unrecognised string both return ``DEFAULT_POLICY``.

    Returns:
        A frozen ``WikiPolicy`` instance. Each registered policy declares its
        own ``mutability`` field at construction time (see ``_ADR_POLICY``
        / ``_AGENT_LIBRARY_POLICY`` / ``_AGENT_INDEX_POLICY`` above); the
        default policy is ``"free"`` (set by the field default). Per-page
        ``mutability_override`` is NOT consulted here — that's a row-level
        concern handled by ``get_effective_mutability``. Storage-layer
        enforcement uses ``get_effective_mutability`` so the row override
        always wins.
    """
    if page_type is None:
        return DEFAULT_POLICY
    return POLICY_BY_TYPE.get(page_type, DEFAULT_POLICY)


@observe(tier="hot")
def is_recall_visible(page: dict, opt_in_tags: Sequence[str] | None = None) -> bool:
    """Return whether *page* may appear in SEARCH results.

    The single rule shared by the unified-recall wiki provider and
    ``wiki_query`` (task 0134 fixed both call sites diverging).

    Car C1 (0047): the opt-in is PER TYPE — an excluded page survives only when
    the caller's ``opt_in_tags`` include its page_type's declared
    ``opt_in_tag`` (a ``WikiPolicy`` field). The page's own ``tags`` field is
    NO LONGER read for the exclusion gate (page tags still matter upstream for
    the SQL pre-filter / HNSW ranking path — unaffected by this car). A type
    with ``opt_in_tag=None`` is excluded unconditionally — no tag unlocks it.
    ``agent_index`` (the TOC) declares ``None``; ``agent_pattern``,
    ``agent_discipline``, and legacy ``agent_prompt`` declare
    ``"agent-prompt"``.

    This narrows the 0134 rule (per-page tag intersection): task 0134 fixed the
    blanket kill-switch, but any-tag intersection still let an excluded page
    survive on an unrelated caller tag. C1 tightens it once more — the unlock
    signal is the TYPE's declared key, not the page's own tags.

    Args:
        page: A wiki page dict; reads ``page_type`` only.
        opt_in_tags: Tags the caller explicitly asked for, if any.

    Returns:
        True when the page may be returned by a search path.
    """
    policy = get_policy(page.get("page_type"))
    if policy.recall_disposition != "exclude":
        return True
    if not opt_in_tags or policy.opt_in_tag is None:
        return False
    return policy.opt_in_tag in set(opt_in_tags)


@observe(tier="hot")
def downweight_multiplier(page: dict, factor: float) -> float:
    """Return the ranking-score multiplier for *page*.

    Car C2 (0047 §7 3b): a downweighted page passes ``is_recall_visible``
    (visibility is unchanged — exclusion still drops only ``"exclude"``) but
    its ranking score is multiplied by *factor* so it sinks below
    ``"include"`` pages of comparable relevance. Returns *factor* (a value
    in (0, 1)) when the page's ``page_type`` resolves to
    ``recall_disposition="downweight"``; ``1.0`` otherwise.

    Single source of truth for the penalty — called from
    ``yadgar.backend.retrieval.providers.fusion`` (unified recall) and
    ``yadgar.core.server.tools.wiki.wiki_query`` (the legacy search tool).
    The *factor* is passed in (not read from settings inside the helper) so
    the helper is testable without a Settings instance and stays in
    ``_shared`` (no config import — ``_shared`` policy stays config-agnostic).

    An excluded page (``recall_disposition="exclude"``) returns ``1.0``
    here on purpose — exclusion is enforced earlier in the pipeline
    (``is_recall_visible`` drops ``exclude`` rows before scoring) so a
    non-1.0 return value can never leak penalty to an excluded row. The
    helper is composable: callers can apply it unconditionally without
    second-guessing the disposition.
    """
    if get_policy(page.get("page_type")).recall_disposition == "downweight":
        return float(factor)
    return 1.0


# ── Car J (0047 §7 D25/D26) — mutability resolver ─────────────────────────────


@observe(tier="hot")
def get_effective_mutability(
    page: dict,
    override: str | None = None,
) -> str:
    """Return the effective mutability for *page*.

    Single source of truth for mutability resolution — called from the
    storage write chokepoint (``_WikiMixin.update_wiki_page``,
    ``insert_wiki_page``, ``delete_wiki_page``) and the
    ``wiki_set_mutability`` tool. Centralised here so storage + tool layer
    share one function (Car J §4.7 refactor).

    Resolution order (later wins):

    1. Per-type default (``MUTABILITY_BY_TYPE[page_type]``) — falls back to
       ``"free"`` for unknown / ``None`` page types.
    2. Per-page override from the wiki_page row's ``mutability_override``
       column — read from *page* dict if present.
    3. Explicit *override* kwarg — lets callers that have already resolved
       the override (e.g. ``WikiStore.set_mutability_by_slug`` passing the
       new value, ``_WikiMixin.update_wiki_page`` reading the row) bypass
       the dict read.

    Returns one of ``"free"``, ``"locked"``, ``"derived"``.
    """
    # Step 1: per-type default
    page_type = page.get("page_type")
    default = MUTABILITY_BY_TYPE.get(page_type or "", MUTABILITY_FREE)

    # Step 2: per-page override from the row dict (read once).
    # ``page.get("mutability_override")`` returns None both when the key is
    # absent (pre-migration rows) and when it is stored as a null — both
    # fall through to the per-type default. Idempotent under migration 030.
    row_override = page.get("mutability_override")

    # Step 3: explicit kwarg wins (None means "no kwarg override")
    if override is not None:
        return override
    if row_override is not None:
        return row_override
    return default


